    def send_json(self, obj):
        body = json.dumps(obj).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def send_file(self, path, mime, rate=0, stall_at=None, stall_secs=0, trickle=False, burst=0):
        """rate: bytes per second (0 = full speed); stall_at: fraction of the file where the server freezes."""
        if not os.path.exists(path):
            self.send_error(404)
            return
        size = os.path.getsize(path)
        start, end = 0, size - 1
        rng = self.headers.get("Range")
        status = 200
        if rng:
            m = re.match(r"bytes=(\d*)-(\d*)", rng)
            if m:
                if m.group(1):
                    start = int(m.group(1))
                if m.group(2):
                    end = int(m.group(2))
                if start >= size:
                    self.send_response(416)
                    self.send_header("Content-Range", "bytes */%d" % size)
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return
                status = 206
        length = end - start + 1
        self.send_response(status)
        self.send_header("Content-Type", mime)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(length))
        if status == 206:
            self.send_header("Content-Range", "bytes %d-%d/%d" % (start, end, size))
        self.end_headers()
        try:
            with open(path, "rb") as f:
                f.seek(start)
                left = length
                pos = start
                # Only a connection that crosses the freeze point freezes (not later reconnects past it).
                stalled = stall_at is None or start >= size * stall_at
                while left > 0:
                    step = 256 * 1024 if not rate else max(4096, rate // 10)
                    if stall_at is not None and not stalled and pos < size * stall_at <= pos + step:
                        step = max(1, int(size * stall_at) - pos)
                    chunk = f.read(min(step, left))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    left -= len(chunk)
                    pos += len(chunk)
                    if stall_at is not None and not stalled and pos >= size * stall_at:
                        stalled = True
                        print("STALL %ds at byte %d%s" % (stall_secs, pos, " (trickle)" if trickle else ""), flush=True)
                        if trickle:
                            # The nasty kind: a few bytes now and then, so no timeout ever fires.
                            end = time.time() + stall_secs
                            while time.time() < end:
                                chunk = f.read(188)
                                if not chunk:
                                    break
                                self.wfile.write(chunk)
                                self.wfile.flush()
                                pos += len(chunk)
                                left -= len(chunk)
                                time.sleep(2)
                        else:
                            time.sleep(stall_secs)
                    if rate and pos - start > burst:
                        time.sleep(len(chunk) / float(rate))
        except (BrokenPipeError, ConnectionResetError):
            pass

